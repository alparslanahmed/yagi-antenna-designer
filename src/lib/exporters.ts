import { PRESETS, type YagiDesign } from './yagi';

/** Download a text blob. */
export function download(filename: string, text: string, mime = 'text/plain'): void {
  const blob = new Blob([text], { type: `${mime};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

export function designFilename(d: YagiDesign, ext: string): string {
  const f =
    d.inputs.frequencyMHz >= 1000
      ? `${(d.inputs.frequencyMHz / 1000).toFixed(3)}GHz`
      : `${d.inputs.frequencyMHz.toFixed(1)}MHz`;
  return `yagi-${d.inputs.elements}el-${f}-${d.inputs.preset}.${ext}`;
}

export function toCsv(d: YagiDesign): string {
  const lines = [
    '# Yagi-Uda cut list — generated by yagi-antenna-designer (open source)',
    `# f0=${d.inputs.frequencyMHz} MHz, lambda=${d.wavelengthMm.toFixed(2)} mm, preset=${PRESETS[d.inputs.preset].name}`,
    `# element dia=${d.inputs.elementDiameterMm} mm, boom dia=${d.inputs.boomDiameterMm} mm (${d.inputs.boomMount}), driven=${d.inputs.drivenType}`,
    `# est gain=${d.gainDbi.toFixed(1)} dBi, F/B=${d.frontToBackDb.toFixed(0)} dB, boom=${d.boomLengthMm.toFixed(0)} mm`,
    'label,role,length_mm,length_lambda,position_mm,position_lambda,spacing_mm',
    ...d.elements.map(
      (e) =>
        `${e.label},${e.role},${e.lengthMm.toFixed(1)},${e.lengthLambda.toFixed(4)},${e.positionMm.toFixed(1)},${e.positionLambda.toFixed(4)},${e.spacingMm.toFixed(1)}`,
    ),
  ];
  return lines.join('\n');
}

/**
 * Minimal NEC-2 deck: straight-wire model of the array, voltage source on
 * the driven element, single-frequency + far-field pattern request.
 * Coordinates in metres: boom along X, elements along Z (horizontal polarisation).
 */
export function toNec(d: YagiDesign): string {
  const f = d.inputs.frequencyMHz;
  const r = d.inputs.elementDiameterMm / 2000; // radius, m
  const lam = d.wavelengthMm / 1000;
  const segFor = (lenM: number) => {
    const n = Math.max(11, Math.round(lenM / (lam / 40)));
    return n % 2 === 0 ? n + 1 : n;
  };
  const fmt = (v: number, p = 5) => {
    const s = v.toFixed(p);
    return s === '-0.00000' ? '0.00000' : s;
  };

  const out: string[] = [];
  out.push('CM ============================================================');
  out.push(
    `CM ${d.inputs.elements}-el Yagi, f0=${f} MHz, ${PRESETS[d.inputs.preset].name}`,
  );
  out.push(
    `CM lambda=${d.wavelengthMm.toFixed(2)} mm  el-dia=${d.inputs.elementDiameterMm} mm  boom=${d.boomLengthMm.toFixed(0)} mm`,
  );
  out.push(
    `CM est gain=${d.gainDbi.toFixed(1)} dBi  F/B=${d.frontToBackDb.toFixed(0)} dB  (parametric estimate)`,
  );
  out.push('CM Straight-wire equivalent (fold modelled straight). Segs ~ lambda/40.');
  out.push('CM Generated by yagi-antenna-designer <https://github.com> - MIT');
  out.push('CE');
  d.elements.forEach((e, i) => {
    const x = e.positionMm / 1000;
    const h = e.lengthMm / 2000;
    const tag = i + 1;
    out.push(
      `GW ${tag} ${segFor(e.lengthMm / 1000)} ${fmt(x)} 0.00000 ${fmt(-h)} ${fmt(x)} 0.00000 ${fmt(h)} ${r.toExponential(3)}`,
    );
  });
  out.push('GS 0 0 1.00000');
  out.push('GE 0');
  // LD card: aluminium conductivity (~3.5e7 S/m) for realism
  out.push('LD 5 0 0 0 3.5e7 0.0');
  const deTag = 2;
  const deSegs = segFor(d.elements[1].lengthMm / 1000);
  out.push(`EX 0 ${deTag} ${(deSegs + 1) / 2} 0 1.00000 0.00000`);
  out.push(`FR 0 1 0 0 ${f.toFixed(4)} 0.0`);
  out.push('RP 0 73 73 1000 0.00000 0.00000 5.00000 5.00000');
  out.push('XQ');
  out.push('EN');
  return out.join('\n');
}
